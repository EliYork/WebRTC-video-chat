import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
const result = await build({
    entryPoints: ['scripts/sfu-client-entry.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: 'ScreenSfuClient',
    outfile: 'src/views/vendor/screen-sfu-client.js',
    legalComments: 'linked',
    metafile: true,
});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs).filter((path) =>
    path.includes('node_modules/')
)) {
    let directory = dirname(resolve(input));
    while (directory !== dirname(directory)) {
        try {
            const manifest = JSON.parse(
                readFileSync(join(directory, 'package.json'), 'utf8')
            );
            if (manifest.name && !packages.has(manifest.name))
                packages.set(manifest.name, { manifest, directory });
            if (manifest.name) break;
        } catch {
            /* keep walking to the dependency's package root */
        }
        directory = dirname(directory);
    }
}
const notices = [
    'Bundled browser SDK: mediasoup-client and dependencies. Generated by npm run build:sfu.',
];
for (const { manifest, directory } of [...packages.values()].sort((a, b) =>
    a.manifest.name.localeCompare(b.manifest.name)
)) {
    notices.push(
        `\n--- ${manifest.name}@${manifest.version} (${manifest.license || 'see license below'}) ---`
    );
    const files = readdirSync(directory).filter((file) =>
        /^(license|licence|copying)(\.|$)/i.test(file)
    );
    if (!files.length)
        throw new Error(`Missing bundled dependency license: ${manifest.name}`);
    files.forEach((file) =>
        notices.push(readFileSync(join(directory, file), 'utf8'))
    );
}
writeFileSync(
    'src/views/vendor/screen-sfu-client.NOTICES.txt',
    notices.join('\n'),
    'utf8'
);
console.log(
    `Built SFU browser SDK with notices for ${packages.size} packages.`
);
